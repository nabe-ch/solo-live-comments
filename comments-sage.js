// 問いかけなら、返事を2つ返す（問いかけでなければ null）
function viewerReplies(text, whole) {
  if (!VIEWER.re.test(text)) return null;
  const pair = whole.slice(-30).match(/([^、。 ]{1,8})と([^、。 ]{1,8}?)(?:は|、| )*(?:どっち|どちら)/);
  if (pair) return [pickFrom(VIEWER.choice).replace('{x}', pair[1]), pickFrom(VIEWER.choice).replace('{x}', pair[2])];
  const pool = /だっけ|教えて|知ってる人|わかる人|分かる人/.test(text) ? VIEWER.unknown : VIEWER.opinion;
  const first = pickFrom(pool);
  return [first, pickFrom(pool.filter((t) => t !== first))];
}
