// 第n土曜など、月の中の決まった曜日の日付
const nthWeekday = (year, month, weekday, n) => {
  const first = new Date(year, month - 1, 1).getDay();
  return 1 + ((weekday - first + 7) % 7) + (n - 1) * 7;
};
// 次に来る開催日（月の一覧と、第n○曜日から探す）
function nextDate(months, weekday, n, now = new Date()) {
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  for (let y = now.getFullYear(); y <= now.getFullYear() + 1; y++) {
    for (const m of [...months].sort((a, b) => a - b)) {
      const date = new Date(y, m - 1, nthWeekday(y, m, weekday, n));
      if (date >= today) return `${y}年${m}月${date.getDate()}日`;
    }
  }
  return '';
}
