const SEASON_SOUTH = (m) => (m >= 9 && m <= 11 ? '春' : m === 12 || m <= 2 ? '夏' : m <= 5 ? '秋' : '冬');

function eventAnswer(rawText) {
  const text = rawText.slice(-40);
  const asksWhen = /いつ|何日|何月|何時|次の|次は|開催|どんな|ある|って何|ってなに/;
  if (/(今|いま).*(季節|何の時期)|(季節|時期).*(今|いま)/.test(text)) {
    const m = new Date().getMonth() + 1;
    return `南半球の${m}月は${SEASON_SOUTH(m)}`;
  }
  for (const ev of EVENTS) if (ev.re.test(text) && asksWhen.test(text)) return `${ev.name}は${ev.when()}`;
  for (const [re, name, when] of CRAFT) if (re.test(text) && asksWhen.test(text)) return `${name}は${when}（南半球）`;
  return null;
}

