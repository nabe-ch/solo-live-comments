// ポケモンのタイプ・世代・進化、「似てる」の答え
function pokemonAnswer(rawText) {
  const text = rawText.slice(-40);
  if (/(似てる|似ている|っぽい|みたい)/.test(text) && /ポケモン|何に|どれに/.test(text)) {
    const last = rememberName(text) || lastName;
    const entry = last && (last.cre || last.fos);
    const name = entry && (entry.c ? entry.c[0] : entry.base);
    const looks = name && lookalikeOf(name);
    if (looks) return `${name}なら${looks.join('か')}に似てるかも`;
    if (last && last.vil && SPECIES_LOOKALIKE[last.vil.v[1]]) return `${last.vil.v[0]}は${last.vil.v[1]}だから、${SPECIES_LOOKALIKE[last.vil.v[1]]}っぽいかも`;
  }
  const poke = pokeList.find((p) => p.re.test(text));
  if (!poke) return null;
  const { id, name: n, types, gen, from } = poke;
  if (/タイプ|属性/.test(text)) return `${n}のタイプは${types}`;
  if (/世代|何作目|いつの/.test(text)) return `${n}は第${gen}世代`;
  if (/何番|番号|図鑑/.test(text)) return `${n}は図鑑${id}番`;
  if (/進化/.test(text)) return from ? `${n}は${from}から進化する` : `${n}は進化前がいない（タマゴから最初の姿）`;
  if (/どんな|何者|って何|ってなに|教えて|知ってる/.test(text)) return `${n}は図鑑${id}番、タイプは${types}、第${gen}世代`;
  return null;
}
